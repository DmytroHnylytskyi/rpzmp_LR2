package ua.kpi.windpower.data

/**
 * Модель сутності вітроенергетичної установки (ВЕУ) у складі вітропарку.
 *
 * Зберігає паспортні технічні параметри турбіни та поточні телеметричні дані SCADA:
 * миттєву швидкість вітру, віддачу потужності, частоту обертання та кут атаки лопатей.
 *
 * @property id Унікальний диспетчерський ідентифікатор установки (наприклад, "WTG-01").
 * @property name Власна диспетчерська назва об'єкта.
 * @property model Промислова марка та серія турбіни.
 * @property ratedPowerKw Встановлена електрична потужність генератора (кВт).
 * @property bladeLengthMeters Геометрична довжина лопаті / радіус ротора (м).
 * @property currentSpeedMps Поточна швидкість вітрового потоку за даними гондольного анемометра (м/с).
 * @property currentPowerKw Поточна активна потужність, що віддається в мережу (кВт).
 * @property rpm Поточна кутова швидкість обертання ротора (об/хв).
 * @property pitchAngleDeg Поточний кут повороту лопатей навколо поздовжньої осі (pitch control, град).
 * @property status Поточний експлуатаційний стан агрегату.
 * @property isInMaintenance Ознака виведення установки у планове технічне обслуговування (керувалась диспетчером).
 */
data class TurbineModel(
    val id: String,
    val name: String,
    val model: String,
    val ratedPowerKw: Double,
    val bladeLengthMeters: Double,
    var currentSpeedMps: Double,
    var currentPowerKw: Double,
    var rpm: Double,
    var pitchAngleDeg: Double,
    var status: TurbineStatus,
    val isInMaintenance: Boolean = false
)

/**
 * Експлуатаційний статус вітрової установки в автоматизованій системі SCADA.
 *
 * @property title Офіційне текстове позначення статусу українською мовою.
 */
enum class TurbineStatus(val title: String) {
    /**
     * Турбіна підключена до загальної енергосистеми та генерує активну потужність.
     */
    OPERATING("Генерація в мережу"),

    /**
     * Швидкість вітру нижча за пускову (Cut-in). Ротор у вільному очікуванні.
     */
    STANDBY("Очікування вітру (Штиль)"),

    /**
     * Автоматична система Pitch-контролю підлаштовує кут атаки лопатей для максимізації віддачі.
     */
    OPTIMIZING("Оптимізація кута атаки"),

    /**
     * Спрацював автоматичний захист від перевантаження або бурі (Cut-out > 25 м/с). Лопаті зафлюговані.
     */
    EMERGENCY_BRAKE("Аварійне гальмування (Буря)"),

    /**
     * Агрегат виведений з експлуатації для планового сервісного чи ремонтного обслуговування.
     */
    MAINTENANCE("Технічне обслуговування")
}
